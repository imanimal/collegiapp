"""Build the Pocket for Windows kit: dot-grid wallpapers and .theme files for Cream (P9) and Night (P11).

Usage: python integrations/windows-pocket/build.py

Writes wallpapers/pocket-cream.png, wallpapers/pocket-night.png (3840x2160) and Pocket Cream.theme,
Pocket Night.theme next to this file. A .theme names its wallpaper by absolute path, so run this again
after moving the folder. Needs Pillow. Colours are the same tokens as ui/js/themes.js (P9, P11).
"""

import pathlib

from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).resolve().parent
W, H, S = 3840, 2160, 2  # 4K, drawn at 2x the app's 1080p measurements

SCHEMES = {
    "cream": {"name": "Pocket Cream", "bg": "#e6e2d8", "text": "#1b1915", "text3": "#6a645a",
              "accent": "#ff5b1f", "mode": "Light"},
    "night": {"name": "Pocket Night", "bg": "#1a1917", "text": "#f4efe5", "text3": "#a39c8d",
              "accent": "#ff6a2b", "mode": "Dark"},
}


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def mix(a, b, t):
    """t of colour a over colour b, like color-mix(in srgb, a t, b)."""
    return tuple(round(x * t + y * (1 - t)) for x, y in zip(rgb(a), rgb(b)))


def dot_tile(size, r_in, r_out, fg, bg):
    """One cell of a radial-gradient dot grid: solid to r_in, fading to r_out, centred in the cell."""
    tile = Image.new("RGB", (size, size), bg)
    px = tile.load()
    c = (size - 1) / 2
    for y in range(size):
        for x in range(size):
            d = ((x - c) ** 2 + (y - c) ** 2) ** .5
            a = 1 if d <= r_in else max(0.0, (r_out - d) / (r_out - r_in))
            if a > 0:
                px[x, y] = tuple(round(f * a + b * (1 - a)) for f, b in zip(fg, bg))
    return tile


def wallpaper(k):
    p = SCHEMES[k]
    bg = rgb(p["bg"])
    img = Image.new("RGB", (W, H), bg)
    # the desk: 16 px dot grid, 1 px dots at 12% ink (pocket.css .content background)
    tile = dot_tile(16 * S, 1 * S, 1.5 * S, mix(p["text"], p["bg"], .12), bg)
    for y in range(0, H, tile.height):
        for x in range(0, W, tile.width):
            img.paste(tile, (x, y))
    # the engraving and speaker grille from the key deck, bottom right, clear of the taskbar. The grille is whole
    # 9 px cells and sits on the desk grid, so neither its holes nor the desk dots around it are cut in half.
    grill = dot_tile(9 * S, 1.7 * S, 2.2 * S, mix(p["text"], p["bg"], .55 * .5), bg)
    gw, gh = 13 * grill.width, 4 * grill.height
    cell = tile.width
    gx, gy = (W - 64 * S - gw) // cell * cell, (H - 132 * S - gh) // cell * cell
    pad = Image.new("RGB", (gw, gh), bg)
    for y in range(0, gh, grill.height):
        for x in range(0, gw, grill.width):
            pad.paste(grill, (x, y))
    mask = Image.new("L", (gw, gh), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, gw - 1, gh - 1), radius=8 * S, fill=255)
    img.paste(pad, (gx, gy), mask)
    try:
        font = ImageFont.truetype("C:/Windows/Fonts/consolab.ttf", round(9.5 * S))
        d = ImageDraw.Draw(img)
        x, label, track = gx - 14 * S, "POCKET CA-1", 9.5 * S * .22
        widths = [d.textlength(ch, font=font) for ch in label]
        x -= sum(widths) + track * (len(label) - 1)
        col = mix(p["text3"], p["bg"], .8)
        for ch, w in zip(label, widths):
            d.text((x, gy + gh / 2), ch, font=font, fill=col, anchor="lm")
            x += w + track
    except OSError:
        pass  # no Consolas: the grille alone still reads as the deck
    out = HERE / "wallpapers" / f"pocket-{k}.png"
    out.parent.mkdir(exist_ok=True)
    img.save(out, optimize=True)
    return out


def theme(k, wall):
    p = SCHEMES[k]
    argb = "0XC4" + p["accent"][1:].upper()
    text = f"""; {p['name']}: Collegiapp's Pocket look for Windows 11. Generated by build.py; double-click to apply.
[Theme]
DisplayName={p['name']}

[Control Panel\\Desktop]
Wallpaper={wall}
TileWallpaper=0
WallpaperStyle=10
Pattern=

[VisualStyles]
Path=%ResourceDir%\\Themes\\Aero\\Aero.msstyles
ColorStyle=NormalColor
Size=NormalSize
AutoColorization=0
ColorizationColor={argb}
SystemMode={p['mode']}
AppMode={p['mode']}
VisualStyleVersion=10

[MasterThemeSelector]
MTSM=RJSPBS

[Sounds]
SchemeName=@%SystemRoot%\\System32\\mmres.dll,-800
"""
    out = HERE / f"{p['name']}.theme"
    out.write_text(text, encoding="utf-8", newline="\r\n")
    return out


if __name__ == "__main__":
    for k in SCHEMES:
        wall = wallpaper(k)
        print("wrote", wall.relative_to(HERE), "and", theme(k, wall).name)
